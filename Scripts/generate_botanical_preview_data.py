#!/usr/bin/env python3
"""
Regenerate GenusPreviewData, SpeciesPreviewData, and CultivarPreviewData from Lists.
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PREVIEW_DIR = ROOT / "Bonsai Hub/ReferenceData/PreviewData"
IMPORT_XLSX = ROOT / "Bonsai Hub/Resources/Import/Bonsai Database Olaf Barmen 3.xlsx"

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lists_botanical_parser import DEFAULT_XLSX, clean_genus_key, parse_botanical_lists


def swift_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_genus_file(genera: list[str]) -> None:
    lines = [
        "//",
        "//  GenusPreviewData.swift",
        "//  Bonsai World",
        "//",
        "//  Lists worksheet — column A (row 4+). Generated by Scripts/generate_botanical_preview_data.py",
        "//",
        "",
        "import Foundation",
        "",
        "enum GenusPreviewData {",
        "    static let namesInListsOrder: [String] = [",
    ]
    for name in genera:
        lines.append(f"        {swift_string(name)},")
    lines += [
        "    ]",
        "",
        "    static let all: [Genus] = namesInListsOrder.enumerated().map { index, name in",
        "        Genus(",
        "            id: ReferencePreviewSeed.id(list: 1, named: name),",
        "            name: name,",
        "            sortOrder: index + 1",
        "        )",
        "    }",
        "",
        "    static func id(named name: String) -> UUID {",
        "        if let match = all.first(where: { $0.name == name }) {",
        "            return match.id",
        "        }",
        "        let key = GenusPreviewData.cleanKey(name)",
        "        guard let match = all.first(where: { cleanKey($0.name) == key }) else {",
        "            preconditionFailure(\"Missing Genus PreviewData for \\(name)\")",
        "        }",
        "        return match.id",
        "    }",
        "",
        "    static func cleanKey(_ raw: String) -> String {",
        "        let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)",
        "        if trimmed == \"Lind\" { return \"Tilia\" }",
        "        if trimmed == \"Caprinus\" { return \"Carpinus\" }",
        "        if let open = trimmed.firstIndex(of: \"(\"), open > trimmed.startIndex {",
        "            return String(trimmed[..<open]).trimmingCharacters(in: .whitespacesAndNewlines)",
        "        }",
        "        return trimmed",
        "    }",
        "}",
        "",
    ]
    (PREVIEW_DIR / "GenusPreviewData.swift").write_text("\n".join(lines), encoding="utf-8")


def genus_display_name(clean: str, genera: list[str]) -> str:
    for name in genera:
        if clean_genus_key(name) == clean:
            return name
    return clean


def write_species_file(
    genera: list[str], species: list[tuple[str, str, str, str]]
) -> None:
    lines = [
        "//",
        "//  SpeciesPreviewData.swift",
        "//  Bonsai World",
        "//",
        "//  Lists worksheet — columns B–AL. Generated by Scripts/generate_botanical_preview_data.py",
        "//",
        "",
        "import Foundation",
        "",
        "enum SpeciesPreviewData {",
        "    private static let rows: [(name: String, code: String, genusName: String)] = [",
    ]
    for _genus, _epithet, binomial, code in species:
        genus_display = genus_display_name(_genus, genera)
        lines.append(
            f"        (name: {swift_string(binomial)}, code: {swift_string(code)}, genusName: {swift_string(genus_display)}),"
        )
    lines += [
        "    ]",
        "",
        "    static let all: [Species] = rows.enumerated().map { index, row in",
        "        Species(",
        "            id: ReferencePreviewSeed.id(list: 2, named: row.name),",
        "            name: row.name,",
        "            genusID: GenusPreviewData.id(named: row.genusName),",
        "            code: row.code,",
        "            sortOrder: index + 1",
        "        )",
        "    }",
        "",
        "    static func id(named name: String) -> UUID {",
        "        guard let match = all.first(where: { $0.name.caseInsensitiveCompare(name) == .orderedSame }) else {",
        "            preconditionFailure(\"Missing Species PreviewData for \\(name)\")",
        "        }",
        "        return match.id",
        "    }",
        "}",
        "",
    ]
    (PREVIEW_DIR / "SpeciesPreviewData.swift").write_text("\n".join(lines), encoding="utf-8")


def write_cultivar_file(cultivars: list[tuple[str, str]]) -> None:
    lines = [
        "//",
        "//  CultivarPreviewData.swift",
        "//  Bonsai World",
        "//",
        "//  Lists worksheet — cultivar columns (row 2 set). Generated by Scripts/generate_botanical_preview_data.py",
        "//",
        "",
        "import Foundation",
        "",
        "enum CultivarPreviewData {",
        "    private static let rows: [(name: String, speciesName: String)] = [",
    ]
    for name, binomial in cultivars:
        lines.append(
            f"        (name: {swift_string(name)}, speciesName: {swift_string(binomial)}),"
        )
    lines += [
        "    ]",
        "",
        "    static let all: [Cultivar] = rows.enumerated().compactMap { index, row in",
        "        guard let species = SpeciesPreviewData.all.first(where: {",
        "            $0.name.caseInsensitiveCompare(row.speciesName) == .orderedSame",
        "        }) else {",
        "            return nil",
        "        }",
        "        return Cultivar(",
        "            id: ReferencePreviewSeed.id(list: 3, named: \"\\(row.speciesName)|\\(row.name)\"),",
        "            name: row.name,",
        "            speciesID: species.id,",
        "            sortOrder: index + 1",
        "        )",
        "    }",
        "}",
        "",
    ]
    (PREVIEW_DIR / "CultivarPreviewData.swift").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_XLSX
    if not source.exists():
        raise SystemExit(f"Workbook not found: {source}")

    IMPORT_XLSX.parent.mkdir(parents=True, exist_ok=True)
    if source.resolve() != IMPORT_XLSX.resolve():
        shutil.copy2(source, IMPORT_XLSX)

    parsed = parse_botanical_lists(source)
    write_genus_file(parsed.genera)
    write_species_file(parsed.genera, parsed.species)
    write_cultivar_file(parsed.cultivars)

    print(
        f"Updated botanical preview data — {len(parsed.genera)} genera, "
        f"{len(parsed.species)} species, {len(parsed.cultivars)} cultivars"
    )


if __name__ == "__main__":
    main()
